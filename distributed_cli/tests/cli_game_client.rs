//! `distributed game-client` / `game-manifest`.
//!
//! The golden surface is the one `distributed_game`'s authoring test writes
//! (`distributed_game/tests/fixtures/authoring.json`); its generated
//! TypeScript is pinned in `tests/fixtures/game-client/sample/`, type-checked
//! by `js` (`npm run check:generated`) and round-tripped against the Rust
//! samples by `js/tests/game-generated.test.mjs`. Regenerate with
//! `UPDATE_GOLDEN=1 cargo test -p distributed_cli --test cli_game_client`.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use distributed_cli::{generate_game_client, ImportExtension};

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).to_path_buf()
}

fn sample_surface() -> String {
    let path = root().join("../distributed_game/tests/fixtures/authoring.json");
    let fixture: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(path).expect("authoring fixture")).unwrap();
    serde_json::to_string_pretty(&fixture["surface"]).unwrap()
}

fn golden_dir() -> PathBuf {
    root().join("tests/fixtures/game-client/sample")
}

fn distributed(args: &[&str]) -> std::process::Output {
    Command::new(env!("CARGO_BIN_EXE_distributed"))
        .args(args)
        .output()
        .expect("distributed should run")
}

#[test]
fn generated_typescript_matches_the_golden_files() {
    let files = generate_game_client(&sample_surface(), ImportExtension::Ts).unwrap();
    let names: Vec<_> = files.iter().map(|f| f.path.as_str()).collect();
    assert_eq!(
        names,
        [
            "client.ts",
            "constants.ts",
            "events.ts",
            "index.ts",
            "input.ts",
            "predict.ts",
            "pures.ts",
            "schema.ts",
            "surface.json"
        ]
    );
    let dir = golden_dir();
    if std::env::var_os("UPDATE_GOLDEN").is_some() {
        fs::create_dir_all(&dir).unwrap();
        for file in &files {
            fs::write(dir.join(&file.path), &file.contents).unwrap();
        }
    }
    for file in &files {
        let golden = fs::read_to_string(dir.join(&file.path)).unwrap_or_default();
        assert_eq!(
            golden, file.contents,
            "{} drifted; regenerate with UPDATE_GOLDEN=1",
            file.path
        );
    }
    // Deterministic: a second run is byte-identical.
    assert_eq!(
        generate_game_client(&sample_surface(), ImportExtension::Ts).unwrap(),
        files
    );
    // Only the SDK is imported from outside the directory.
    for file in files.iter().filter(|f| f.path.ends_with(".ts")) {
        for line in file
            .contents
            .lines()
            .filter(|l| l.starts_with("import ") || l.starts_with("export * from"))
        {
            assert!(
                line.contains("'@hops-ops/distributed/game'") || line.contains("'./"),
                "{}: unexpected import {line}",
                file.path
            );
        }
    }
}

#[test]
fn import_extension_is_configurable() {
    let js = generate_game_client(&sample_surface(), ImportExtension::Js).unwrap();
    let index = js.iter().find(|f| f.path == "index.ts").unwrap();
    assert!(index.contents.contains("export * from './schema.js';"));
    let none = generate_game_client(&sample_surface(), ImportExtension::None).unwrap();
    let index = none.iter().find(|f| f.path == "index.ts").unwrap();
    assert!(index.contents.contains("export * from './schema';"));
}

#[test]
fn check_mode_detects_drift_and_write_keeps_foreign_files() {
    let tmp = tempfile::tempdir().unwrap();
    let manifest = tmp.path().join("surface.json");
    fs::write(&manifest, sample_surface()).unwrap();
    let out = tmp.path().join("gen");
    let (m, o) = (manifest.to_str().unwrap(), out.to_str().unwrap());

    let check = distributed(&["game-client", "--manifest", m, "--out", o, "--check"]);
    assert!(!check.status.success());
    assert!(String::from_utf8_lossy(&check.stderr).contains("missing schema.ts"));

    assert!(distributed(&["game-client", "--manifest", m, "--out", o])
        .status
        .success());
    assert!(
        distributed(&["game-client", "--manifest", m, "--out", o, "--check"])
            .status
            .success()
    );

    // Regenerating identical output does not rewrite (or touch) any file.
    let modified = |name: &str| fs::metadata(out.join(name)).unwrap().modified().unwrap();
    let before = modified("schema.ts");
    std::thread::sleep(std::time::Duration::from_millis(20));
    assert!(distributed(&["game-client", "--manifest", m, "--out", o])
        .status
        .success());
    assert_eq!(modified("schema.ts"), before);

    fs::write(out.join("events.ts"), "// edited").unwrap();
    fs::write(
        out.join("stale.ts"),
        "// @generated by `distributed game-client` (old)",
    )
    .unwrap();
    let check = distributed(&["game-client", "--manifest", m, "--out", o, "--check"]);
    let stderr = String::from_utf8_lossy(&check.stderr);
    assert!(!check.status.success());
    assert!(stderr.contains("changed events.ts"), "{stderr}");
    assert!(stderr.contains("unexpected stale.ts"), "{stderr}");

    // Regenerating removes stale generated files...
    assert!(distributed(&["game-client", "--manifest", m, "--out", o])
        .status
        .success());
    assert!(!out.join("stale.ts").exists());
    // ...but refuses to delete files it did not generate.
    fs::write(out.join("mine.ts"), "export const x = 1;").unwrap();
    let write = distributed(&["game-client", "--manifest", m, "--out", o]);
    assert!(!write.status.success());
    assert!(out.join("mine.ts").exists());
}

#[test]
fn invalid_surfaces_are_rejected() {
    let tmp = tempfile::tempdir().unwrap();
    let manifest = tmp.path().join("surface.json");
    fs::write(&manifest, r#"{"schemaVersion": 9}"#).unwrap();
    let out = tmp.path().join("gen");
    let run = distributed(&[
        "game-client",
        "--manifest",
        manifest.to_str().unwrap(),
        "--out",
        out.to_str().unwrap(),
    ]);
    assert!(!run.status.success());
    assert!(String::from_utf8_lossy(&run.stderr).contains("schemaVersion"));
}

#[test]
#[ignore = "compiles the fixture via the manifest harness; run in the integration job"]
fn game_manifest_runs_the_surface_export() {
    let manifest = root().join("tests/fixtures/game-surface/Cargo.toml");
    let tmp = tempfile::tempdir().unwrap();
    let out = tmp.path().join("orbs.json");
    let run = distributed(&[
        "game-manifest",
        "--manifest-path",
        manifest.to_str().unwrap(),
        "--out",
        out.to_str().unwrap(),
    ]);
    assert!(
        run.status.success(),
        "{}",
        String::from_utf8_lossy(&run.stderr)
    );
    let surface: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(&out).unwrap()).unwrap();
    assert_eq!(surface["schemaVersion"], 3);
    assert_eq!(surface["name"], "orbs");
    assert_eq!(surface["predict"]["export"], "orb_step");
    assert_eq!(surface["predict"]["package"], "game-surface-fixture");
    assert_eq!(surface["pures"][0]["export"], "orb_radius");
    assert_eq!(surface["constants"][0]["value"]["limit"], 32.0);
    assert_eq!(
        surface["kinds"][0]["fields"][0]["correction"]["durationMs"],
        80
    );
    assert_eq!(surface["input"]["fields"][1]["buttons"][0], "boost");
    assert_eq!(surface["events"][0]["name"], "hello");
    let gen = tmp.path().join("gen");
    let run = distributed(&[
        "game-client",
        "--manifest",
        out.to_str().unwrap(),
        "--out",
        gen.to_str().unwrap(),
    ]);
    assert!(
        run.status.success(),
        "{}",
        String::from_utf8_lossy(&run.stderr)
    );
    assert!(fs::read_to_string(gen.join("client.ts"))
        .unwrap()
        .contains("createOrbsClient"));

    // The predicted step and the pure function compile to one
    // self-contained module next to the client (game-wasm checks both
    // exports); a second run is a stamp hit, and --check verifies it.
    let wasm = |extra: &[&str]| {
        let mut args = vec![
            "game-wasm",
            "--manifest",
            out.to_str().unwrap(),
            "--manifest-path",
            manifest.to_str().unwrap(),
            "--out",
            gen.to_str().unwrap(),
        ];
        args.extend(extra);
        distributed(&args)
    };
    let check = wasm(&["--check"]);
    assert!(!check.status.success(), "nothing built yet");
    let build = wasm(&[]);
    assert!(
        build.status.success(),
        "{}",
        String::from_utf8_lossy(&build.stderr)
    );
    let module = fs::read(gen.join("wasm/orbs.wasm")).unwrap();
    assert_eq!(&module[..4], b"\0asm");
    let again = wasm(&[]);
    assert!(String::from_utf8_lossy(&again.stdout).contains("is current"));
    assert!(wasm(&["--check"]).status.success());
    fs::write(gen.join("wasm/orbs.wasm"), b"tampered").unwrap();
    assert!(
        !wasm(&["--check"]).status.success(),
        "a changed module is stale"
    );
}

#[test]
fn game_wasm_needs_something_to_compile() {
    let tmp = tempfile::tempdir().unwrap();
    let mut surface: serde_json::Value = serde_json::from_str(&sample_surface()).unwrap();
    surface.as_object_mut().unwrap().remove("predict");
    surface.as_object_mut().unwrap().remove("pures");
    let manifest = tmp.path().join("surface.json");
    fs::write(&manifest, surface.to_string()).unwrap();
    let run = distributed(&[
        "game-wasm",
        "--manifest",
        manifest.to_str().unwrap(),
        "--out",
        tmp.path().join("gen").to_str().unwrap(),
    ]);
    assert!(!run.status.success());
    assert!(
        String::from_utf8_lossy(&run.stderr).contains("declares nothing to compile"),
        "{}",
        String::from_utf8_lossy(&run.stderr)
    );
}

#[test]
#[ignore = "compiles the fixture via the manifest harness; run in the integration job"]
fn concurrent_game_manifests_export_their_own_entrypoints() {
    // Every entrypoint of a package shares one harness directory; without
    // the harness lock, concurrent runs overwrote each other's `main.rs` and
    // exported the last writer's surface.
    let manifest = root().join("tests/fixtures/game-surface/Cargo.toml");
    let tmp = tempfile::tempdir().unwrap();
    // Warm the harness build so the concurrent runs race on `main.rs`, not
    // on the first compile.
    let warm = distributed(&[
        "game-manifest",
        "--manifest-path",
        manifest.to_str().unwrap(),
        "--out",
        tmp.path().join("warm.json").to_str().unwrap(),
    ]);
    assert!(
        warm.status.success(),
        "{}",
        String::from_utf8_lossy(&warm.stderr)
    );
    for round in 0..4 {
        let runs: Vec<_> = [("game_surface", "orbs"), ("bare_surface", "bare")]
            .into_iter()
            .flat_map(|pair| [pair, pair])
            .enumerate()
            .map(|(i, (entrypoint, name))| {
                let out = tmp.path().join(format!("{round}-{i}.json"));
                let child = Command::new(env!("CARGO_BIN_EXE_distributed"))
                    .args([
                        "game-manifest",
                        "--manifest-path",
                        manifest.to_str().unwrap(),
                        "--entrypoint",
                        entrypoint,
                        "--out",
                        out.to_str().unwrap(),
                    ])
                    .stderr(std::process::Stdio::piped())
                    .spawn()
                    .expect("distributed should run");
                (child, out, name)
            })
            .collect();
        for (child, out, name) in runs {
            let output = child.wait_with_output().unwrap();
            assert!(
                output.status.success(),
                "{}",
                String::from_utf8_lossy(&output.stderr)
            );
            let surface: serde_json::Value =
                serde_json::from_str(&fs::read_to_string(&out).unwrap()).unwrap();
            assert_eq!(surface["name"], name, "round {round}: {}", out.display());
        }
    }
}
