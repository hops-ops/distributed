//! `leaderboards.ts`: typed documents for the manifest's leaderboard roots.
//!
//! Leaderboard results are ranked by the server (Redis sorted sets) and are
//! not normalized read-model rows, so they are plain GraphQL operations with
//! exact documents, variable and data types, and an `@live` subscription
//! document where the surface has one. They never enter the replica cache.

use super::common::json_string;
use crate::client_compiler::manifest::{
    ClientManifest, ManifestLeaderboard, ManifestLeaderboardRoot, LEADERBOARD_ENTRY_TYPENAME,
};
use crate::client_compiler::ClientCompileError;

/// `None` when the manifest has no leaderboards.
pub(super) fn render_leaderboards(
    manifest: &ClientManifest,
) -> Result<Option<String>, ClientCompileError> {
    if manifest.leaderboards.is_empty() {
        return Ok(None);
    }
    let mut out = vec![
        "/** GENERATED by distributed client. Server-ranked leaderboard queries; not replica-cached. */".to_string(),
        format!(
            "export interface {LEADERBOARD_ENTRY_TYPENAME} {{\n\
             \t/** Zero-based rank in the board's order. */\n\
             \treadonly rank: number;\n\
             \treadonly member: string;\n\
             \treadonly score: number;\n\
             }}"
        ),
    ];
    let mut index = Vec::new();
    for leaderboard in &manifest.leaderboards {
        for root in &leaderboard.roots {
            let (block, export) = render_root(manifest, leaderboard, root)?;
            out.push(block);
            index.push(format!("\t{}: {export},", json_string(&root.name)?));
        }
    }
    out.push(format!(
        "export const LEADERBOARD_OPERATIONS = {{\n{}\n}} as const;",
        index.join("\n")
    ));
    Ok(Some(format!("{}\n", out.join("\n\n"))))
}

fn pascal(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}

fn render_root(
    manifest: &ClientManifest,
    leaderboard: &ManifestLeaderboard,
    root: &ManifestLeaderboardRoot,
) -> Result<(String, String), ClientCompileError> {
    let operation = pascal(&root.name);
    let variables = root
        .arguments
        .iter()
        .map(|argument| {
            let ty = if argument.type_name == "Int" {
                "number"
            } else {
                "string"
            };
            if argument.nullable {
                format!("readonly {}?: {ty} | null;", argument.name)
            } else {
                format!("readonly {}: {ty};", argument.name)
            }
        })
        .collect::<Vec<_>>();
    let definitions = root
        .arguments
        .iter()
        .map(|argument| {
            format!(
                "${}: {}{}",
                argument.name,
                argument.type_name,
                if argument.nullable { "" } else { "!" }
            )
        })
        .collect::<Vec<_>>();
    let (definitions, call) = if root.arguments.is_empty() {
        (String::new(), String::new())
    } else {
        (
            format!("({})", definitions.join(", ")),
            format!(
                "({})",
                root.arguments
                    .iter()
                    .map(|argument| format!("{0}: ${0}", argument.name))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
        )
    };
    let selection = format!("{}{call} {{ rank member score }}", root.name);
    let document = format!("query {operation}{definitions} {{ {selection} }}");
    let live = root
        .live
        .then(|| format!("subscription {operation}_Live{definitions} {{ {selection} }}"));
    let data_type = if root.list {
        format!("readonly {LEADERBOARD_ENTRY_TYPENAME}[]")
    } else {
        format!("{LEADERBOARD_ENTRY_TYPENAME} | null")
    };
    let export = format!("{operation}Leaderboard");
    let block = format!(
        "export type {operation}Variables = {{{}}};\n\
         export type {operation}Data = {{ readonly {}: {data_type} }};\n\
         export const {export} = {{\n\
         \tleaderboard: {},\n\
         \toperation: {},\n\
         \torder: {},\n\
         \tlimits: {{ defaultFirst: {}, maxFirst: {}, maxRadius: {} }},\n\
         \tdocument: {},\n\
         \tliveDocument: {},\n\
         \tschemaHash: {},\n\
         }} as const;",
        if variables.is_empty() {
            String::new()
        } else {
            format!(" {} ", variables.join(" "))
        },
        root.name,
        json_string(&leaderboard.name)?,
        json_string(&root.operation)?,
        json_string(&leaderboard.order)?,
        leaderboard.default_first,
        leaderboard.max_first,
        leaderboard.max_radius,
        json_string(&document)?,
        match &live {
            Some(live) => json_string(live)?,
            None => "null".to_string(),
        },
        json_string(&manifest.schema_fingerprint)?,
    );
    Ok((block, export))
}
