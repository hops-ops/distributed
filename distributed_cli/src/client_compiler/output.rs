//! Writing and checking a compiled client project on disk.
//!
//! The compiler itself stays pure; this is the only part of the module that
//! touches the filesystem, and it does so through [`GeneratedDir`].

use std::collections::BTreeSet;
use std::error::Error;
use std::fs;
use std::path::{Component, Path};

use super::GeneratedClientProject;
use crate::generated_dir::GeneratedDir;

const MAX_PROVENANCE_BYTES: u64 = 16 * 1024 * 1024;
const OWNERSHIP_MARKER: &str = "/** GENERATED by distributed client. Do not edit. */";

/// Make `root` hold exactly the compiled project.
///
/// An operation module the previous run recorded in `manifest.json`, and that
/// still carries the compiler's marker, is removed when its operation is gone.
/// Any other file the project does not contain makes the write fail before
/// anything changes: a missing or unreadable record never authorizes a
/// deletion.
pub(crate) fn write_client_project(
    root: &Path,
    project: &GeneratedClientProject,
) -> Result<(), Box<dyn Error>> {
    let previous = previous_operation_modules(root)?;
    // Provenance is written last so an interrupted run never advertises a new
    // complete generation before its operation modules exist.
    let mut files = project.files.clone();
    files.sort_by(|left, right| {
        (left.path == "manifest.json", &left.path)
            .cmp(&(right.path == "manifest.json", &right.path))
    });
    client_dir(root).write(&files, |path, contents| {
        if !previous.contains(path) {
            return Ok(false);
        }
        if !contents.starts_with(OWNERSHIP_MARKER) {
            return Err(format!(
                "refusing to remove {} because its compiler ownership marker is missing",
                root.join(path).display()
            )
            .into());
        }
        Ok(true)
    })
}

/// Fail unless `root` holds exactly the compiled project. Reads only.
pub(crate) fn check_client_project(
    root: &Path,
    project: &GeneratedClientProject,
) -> Result<(), Box<dyn Error>> {
    let drift = client_dir(root).drift(&project.files)?;
    if drift.is_empty() {
        return Ok(());
    }
    Err(format!(
        "generated Distributed client artifacts are stale:\n  {}\nrun `distributed client` without --check to regenerate",
        drift.join("\n  ")
    )
    .into())
}

fn client_dir(root: &Path) -> GeneratedDir<'_> {
    GeneratedDir { root, nested: true }
}

/// The operation modules the previous run recorded in `<root>/manifest.json`.
/// Empty when there was no previous run.
fn previous_operation_modules(root: &Path) -> Result<BTreeSet<String>, Box<dyn Error>> {
    let path = root.join("manifest.json");
    let refuse = |problem: &str| -> Box<dyn Error> {
        format!(
            "previous generated client manifest {} {problem}; refusing to guess stale-file ownership",
            path.display()
        )
        .into()
    };
    let metadata = match fs::symlink_metadata(&path) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(BTreeSet::new()),
        Err(error) => return Err(refuse(&format!("cannot be inspected: {error}"))),
    };
    if !metadata.is_file() || metadata.len() > MAX_PROVENANCE_BYTES {
        return Err(refuse("must be a regular file of at most 16 MiB"));
    }
    let provenance: serde_json::Value = serde_json::from_slice(
        &fs::read(&path).map_err(|error| refuse(&format!("cannot be read: {error}")))?,
    )
    .map_err(|error| refuse(&format!("cannot be parsed: {error}")))?;
    if provenance
        .get("compiler_manifest_version")
        .and_then(serde_json::Value::as_u64)
        != Some(2)
    {
        return Err(refuse("has an unsupported compiler_manifest_version"));
    }
    let operations = provenance
        .get("operations")
        .and_then(serde_json::Value::as_array)
        .ok_or_else(|| refuse("is missing operations"))?;
    let mut modules = BTreeSet::new();
    for (index, operation) in operations.iter().enumerate() {
        let module = operation
            .get("module_path")
            .and_then(serde_json::Value::as_str)
            .ok_or_else(|| refuse(&format!("operations[{index}] is missing module_path")))?;
        let mut components = Path::new(module).components();
        let is_operation_module = matches!(components.next(), Some(Component::Normal(directory)) if directory == "operations")
            && matches!(components.next(), Some(Component::Normal(file)) if Path::new(file).extension().is_some_and(|extension| extension == "ts"))
            && components.next().is_none();
        if !is_operation_module {
            return Err(format!(
                "previous compiler provenance contains unsafe operation module path `{module}`; refusing to remove it"
            )
            .into());
        }
        modules.insert(module.to_string());
    }
    Ok(modules)
}
