//! Embeds `migrations/inventory.json` as `EmbeddedMigration` registrations
//! (`OUT_DIR/migration_inventory.rs`) and runs gRPC codegen for `grpc`.
//!
//! The inventory is trusted repository input. The build checks only what the
//! registration needs: consecutive versions, each path inside its dialect
//! directory, each file's recorded SHA-256 (an edited released migration
//! fails the build instead of silently changing), and no `.sql` file in a
//! dialect directory left unregistered (it would never run).

use serde::Deserialize;
use sha2::{Digest, Sha256};
use std::fs;
use std::path::{Component, Path, PathBuf};

const INVENTORY_PATH: &str = "migrations/inventory.json";
const INVENTORY_VERSION: u32 = 1;

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Inventory {
    schema_version: u32,
    migrations: Vec<Migration>,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct Migration {
    version: u64,
    description: String,
    sqlite: MigrationFile,
    postgres: MigrationFile,
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct MigrationFile {
    path: String,
    sha256: String,
}

#[derive(Clone, Copy)]
enum Dialect {
    Sqlite,
    Postgres,
}

impl Dialect {
    const ALL: [Self; 2] = [Self::Sqlite, Self::Postgres];

    const fn directory(self) -> &'static str {
        match self {
            Self::Sqlite => "migrations/sqlite",
            Self::Postgres => "migrations/postgres",
        }
    }

    fn file(self, migration: &Migration) -> &MigrationFile {
        match self {
            Self::Sqlite => &migration.sqlite,
            Self::Postgres => &migration.postgres,
        }
    }
}

fn main() {
    emit_migration_inventory();

    // Only run gRPC codegen when the "grpc" feature is enabled.
    // Cargo sets CARGO_FEATURE_GRPC when compiling with --features grpc.
    if std::env::var("CARGO_FEATURE_GRPC").is_ok() {
        let service = tonic_build::manual::Service::builder()
            .name("CommandService")
            .package("sourced.microsvc")
            .method(
                tonic_build::manual::Method::builder()
                    .name("dispatch")
                    .route_name("Dispatch")
                    .input_type("crate::microsvc::grpc::GrpcRequest")
                    .output_type("crate::microsvc::grpc::GrpcResponse")
                    .codec_path("tonic_prost::ProstCodec")
                    .build(),
            )
            .method(
                tonic_build::manual::Method::builder()
                    .name("health")
                    .route_name("Health")
                    .input_type("crate::microsvc::grpc::HealthRequest")
                    .output_type("crate::microsvc::grpc::HealthResponse")
                    .codec_path("tonic_prost::ProstCodec")
                    .build(),
            )
            .build();

        tonic_build::manual::Builder::new().compile(&[service]);
    }
}

fn emit_migration_inventory() {
    println!("cargo:rerun-if-changed={INVENTORY_PATH}");
    let root = PathBuf::from(
        std::env::var_os("CARGO_MANIFEST_DIR")
            .expect("Cargo must provide CARGO_MANIFEST_DIR to the build script"),
    );
    let bytes = fs::read(root.join(INVENTORY_PATH))
        .unwrap_or_else(|error| panic!("read {INVENTORY_PATH}: {error}"));
    let inventory: Inventory = serde_json::from_slice(&bytes)
        .unwrap_or_else(|error| panic!("parse {INVENTORY_PATH}: {error}"));
    validate_inventory(&root, &inventory);

    let mut generated =
        String::from("// Generated by build.rs from migrations/inventory.json; do not edit.\n");
    emit_dialect(
        &mut generated,
        "SQLITE_MIGRATIONS",
        Dialect::Sqlite,
        &inventory,
    );
    emit_dialect(
        &mut generated,
        "POSTGRES_MIGRATIONS",
        Dialect::Postgres,
        &inventory,
    );
    let out_dir = PathBuf::from(
        std::env::var_os("OUT_DIR").expect("Cargo must provide OUT_DIR to the build script"),
    );
    fs::write(out_dir.join("migration_inventory.rs"), generated)
        .unwrap_or_else(|error| panic!("write generated migration registration: {error}"));
}

fn emit_dialect(generated: &mut String, name: &str, dialect: Dialect, inventory: &Inventory) {
    match dialect {
        Dialect::Sqlite => generated.push_str("#[cfg(any(feature = \"sqlite\", all(feature = \"cloudflare-workers\", target_arch = \"wasm32\")))]\n"),
        Dialect::Postgres => generated.push_str("#[cfg(feature = \"postgres\")]\n"),
    }
    generated.push_str("pub(crate) const ");
    generated.push_str(name);
    generated.push_str(": &[EmbeddedMigration] = &[\n");
    for migration in &inventory.migrations {
        let file = dialect.file(migration);
        generated.push_str("    EmbeddedMigration { version: ");
        generated.push_str(&migration.version.to_string());
        generated.push_str(", description: ");
        generated.push_str(&format!("{:?}", migration.description));
        generated.push_str(", sql: include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/\", ");
        generated.push_str(&format!("{:?}", file.path));
        generated.push_str(")), },\n");
    }
    generated.push_str("];\n");
}

fn validate_inventory(root: &Path, inventory: &Inventory) {
    if inventory.schema_version != INVENTORY_VERSION {
        panic!(
            "{INVENTORY_PATH} schema version {} is unsupported; expected {INVENTORY_VERSION}",
            inventory.schema_version
        );
    }
    if inventory.migrations.is_empty() {
        panic!("{INVENTORY_PATH} must contain at least one migration");
    }
    for (index, migration) in inventory.migrations.iter().enumerate() {
        let expected = (index + 1) as u64;
        if migration.version != expected {
            panic!(
                "{INVENTORY_PATH} versions must be consecutive: expected {expected}, observed {}",
                migration.version
            );
        }
        for dialect in Dialect::ALL {
            let file = dialect.file(migration);
            println!("cargo:rerun-if-changed={}", file.path);
            let path = Path::new(&file.path);
            if !file.path.ends_with(".sql")
                || !path.starts_with(dialect.directory())
                || !path
                    .components()
                    .all(|component| matches!(component, Component::Normal(_)))
            {
                panic!(
                    "{INVENTORY_PATH} migration path `{}` is outside `{}`",
                    file.path,
                    dialect.directory()
                );
            }
            let sql = fs::read(root.join(path))
                .unwrap_or_else(|error| panic!("read migration `{}`: {error}", file.path));
            let observed = sha256_hex(&sql);
            if observed != file.sha256 {
                panic!(
                    "{INVENTORY_PATH} migration `{}` checksum mismatch: expected {}, observed {observed}",
                    file.path, file.sha256
                );
            }
        }
    }
    // A migration written but not registered would never run.
    for dialect in Dialect::ALL {
        let directory = dialect.directory();
        println!("cargo:rerun-if-changed={directory}");
        let entries = fs::read_dir(root.join(directory))
            .unwrap_or_else(|error| panic!("read `{directory}`: {error}"));
        for entry in entries {
            let entry = entry.unwrap_or_else(|error| panic!("read `{directory}`: {error}"));
            let name = entry.file_name();
            let Some(name) = name.to_str().filter(|name| name.ends_with(".sql")) else {
                continue;
            };
            let path = format!("{directory}/{name}");
            if !inventory
                .migrations
                .iter()
                .any(|migration| dialect.file(migration).path == path)
            {
                panic!("`{path}` is not registered in {INVENTORY_PATH}");
            }
        }
    }
}

fn sha256_hex(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}
