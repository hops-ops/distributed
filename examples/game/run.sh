#!/usr/bin/env bash
# distributed_game demos — one command per demo (dev only).
#
#   ./run.sh mobpit         Mob Pit: its rooms run on celld (`celld dev`, the
#                           cells worker hosts one Durable Object per room),
#                           the services (tickets, read models, boards) and
#                           Vite; `leaderboard` = same, board page
#   ./run.sh mobpit --fleet [N]
#                           same on a local multi-node celld: N nodes (default
#                           3) in production mode on one RustFS bucket
#                           (docker compose), entered round-robin, so rooms
#                           land on different nodes (debug overlay shows which)
#   ./run.sh gen            regenerate client/src/generated/<surface>/ from the
#                           Rust surfaces (`distributed game-manifest` +
#                           `distributed game-client`) and compile each
#                           surface's `#[predict]` step and `#[game_pure]`
#                           functions to <surface>/wasm/<surface>.wasm
#                           (`distributed game-wasm`, gitignored, stamped so
#                           an unchanged module is not rebuilt); `gen --check`
#                           verifies the TypeScript (and still builds WASM)
#   ./run.sh sveltekit [--fleet [N]]
#                           Mob Pit in SvelteKit (sveltekit/): dev sign-in,
#                           session-minted tickets, game client generated by
#                           the Vite plugin, Svelte HUD, and the settled
#                           read model from mobpit-service over GraphQL @live
#                           (`distributed dev server/` runs the service + UI)
#   ./run.sh smoke          every demo's smoke tests (Rust bots + headless JS,
#                           generated clients checked, SvelteKit headless)
#   ./run.sh list           demos this script knows
#
# Env: GAME_DEMOS_PORT (server, default 2567), GAME_DEMOS_CLIENT_PORT (Vite,
# default 5173), DG_NET_LATENCY_MS / DG_NET_JITTER_MS / DG_NET_LOSS (initial
# server NetSim; the HUD sliders change it live), MOBPIT_DATA_DIR (Mob Pit /
# Leaderboard local files and their `celld dev` state, default
# examples/game/.data/mobpit), REDIS_URL (Redis leaderboard instead of
# in-memory; required by `sveltekit` and `smoke`, whose SvelteKit
# leaderboard is the Redis board served through GraphQL), SVELTEKIT_PORT (SvelteKit demo, default 5573; its game server
# uses GAME_DEMOS_PORT, default 2967 there, and its read-model service
# MOBPIT_SERVICE_PORT, default GAME_DEMOS_PORT + 2).
#
# celld: Mob Pit's rooms and the demos' durable cells (examples/game/cells:
# Mob Pit's rooms, Crawler, presence, zone-activity and hood / borough /
# city tier cells, the world's content rollout) run on celld, never natively; state persists in
# .data/<demo>/celld (Mob Pit: MOBPIT_DATA_DIR/celld, the fleet's bucket in
# a RustFS volume of its compose project). Fleet ports: nodes' public
# listeners GAME_DEMOS_PORT + 10.., operators + 20.., RustFS + 30
# (MOBPIT_FLEET_S3_PORT); `docker compose down -v` runs on exit. CELLD_BIN names the binary (default: `celld` on
# PATH; the version pinned in .celld-version, checked by
# scripts/celld.sh), CELLD_PORT its port (default
# GAME_DEMOS_PORT + 3),
# CELLD_ESBUILD its bundler (default: the client's esbuild). The worker is
# built with worker-build (`cargo install worker-build --locked`).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "$HERE/../.." && pwd)"
SERVER="$HERE/server"
CLIENT="$HERE/client"
SVELTEKIT="$HERE/sveltekit"
BIN="$SERVER/target/debug/game-demos"
SERVICE_BIN="$SERVER/target/debug/mobpit-service"
CELLS="$HERE/cells"
DEMOS=(mobpit leaderboard)
export MOBPIT_DATA_DIR="${MOBPIT_DATA_DIR:-$HERE/.data/mobpit}"
# Game surfaces with a generated client (`game_demos::<surface>::game_surface`);
# the leaderboard page uses Mob Pit's.
SURFACES=(mobpit)
CLI="$REPO/target/debug/distributed"

log() { printf '\033[1;36m[demos]\033[0m %s\n' "$*"; }

ensure_sdk() {
	# The client depends on the local SDK build (file:../../../js).
	if [[ ! -d "$REPO/js/node_modules" ]]; then
		log "installing js SDK dependencies"
		(cd "$REPO/js" && npm ci --no-audit --no-fund)
	fi
	local marker="$REPO/js/dist/game/index.js"
	if [[ ! -f "$marker" ]] || [[ -n "$(find "$REPO/js/src" -newer "$marker" -name '*.ts' -print -quit)" ]]; then
		log "building js SDK"
		(cd "$REPO/js" && npm run build >/dev/null)
	fi
}

ensure_client() {
	local stamp="$CLIENT/node_modules/.package-lock.json"
	if [[ ! -f "$stamp" ]] || [[ "$CLIENT/package-lock.json" -nt "$stamp" ]]; then
		log "installing client dependencies (npm ci)"
		(cd "$CLIENT" && npm ci --no-audit --no-fund)
	fi
}

ensure_sveltekit() {
	local stamp="$SVELTEKIT/node_modules/.package-lock.json"
	if [[ ! -f "$stamp" ]] || [[ "$SVELTEKIT/package-lock.json" -nt "$stamp" ]]; then
		log "installing SvelteKit demo dependencies (npm ci)"
		(cd "$SVELTEKIT" && npm ci --no-audit --no-fund)
	fi
}

# ensure_celld: resolve CELLD_BIN (the pinned celld, `.celld-version`) and
# CELLD_ESBUILD. scripts/celld.sh prints the upgrade command on a mismatch.
ensure_celld() {
	CELLD_BIN="$("$REPO/scripts/celld.sh" check "${CELLD_BIN:-}")" || exit 1
	if [[ -z "${CELLD_ESBUILD:-}" ]]; then
		ensure_client
		CELLD_ESBUILD="$CLIENT/node_modules/.bin/esbuild"
	fi
	export CELLD_BIN CELLD_ESBUILD
}

# ensure_cells: build the demos' cells worker (examples/game/cells) when its
# sources changed.
ensure_cells() {
	local marker="$CELLS/build/worker/shim.mjs"
	if [[ ! -f "$marker" ]] || [[ -n "$(find "$CELLS/src" "$CELLS/Cargo.toml" "$SERVER/crawler" "$SERVER/rooms" "$SERVER/sim" "$SERVER/tiers" "$REPO/src" "$REPO/distributed_game/src" -newer "$marker" -name '*.rs' -print -quit 2>/dev/null)" ]] ||
		[[ "$CELLS/Cargo.toml" -nt "$marker" ]]; then
		command -v worker-build >/dev/null || {
			echo "worker-build not found: cargo install worker-build --locked" >&2
			exit 1
		}
		log "building the demos' cells worker (worker-build)"
		(cd "$CELLS" && worker-build --release >/dev/null)
	fi
}

# kill_tree <pid>: stop a process and every descendant (celld dev starts its
# node in a session of its own, so collect the tree while the root is stopped).
kill_tree() {
	local root="$1" pids=() frontier=("$1") next pid
	kill -STOP "$root" 2>/dev/null || return 0
	while ((${#frontier[@]})); do
		next=()
		for pid in "${frontier[@]}"; do
			pids+=("$pid")
			while read -r child; do next+=("$child"); done < <(pgrep -P "$pid" 2>/dev/null || true)
		done
		frontier=("${next[@]+"${next[@]}"}")
	done
	kill -KILL "${pids[@]}" 2>/dev/null || true
}

# warn_celld_state <state dir>: a `celld dev` state only grows (celld keeps
# every write; epoch GC stalls rooms while it runs). Past a few hundred
# cells or ~100 MB, rooms drop ticks and a restart takes minutes (a
# 255-cell, 216 MB state never became ready) to answer (client/tests/mobpit-soak-headless.test.mjs). Say so and how
# to reset; never reset on its own.
warn_celld_state() {
	local state="$1" cells=0 mb=0
	[[ -d "$state/runtime" ]] && cells=$(find "$state/runtime" -mindepth 1 -maxdepth 1 | wc -l | tr -d ' ')
	[[ -f "$state/objects.sqlite3" ]] && mb=$(($(wc -c <"$state/objects.sqlite3") / 1048576))
	if ((cells > ${CELLD_STATE_WARN_CELLS:-500} || mb > ${CELLD_STATE_WARN_MB:-100})); then
		printf '\033[1;33m[demos]\033[0m celld dev state is large (%s cells, %s MB): rooms may stutter and a restart\n' "$cells" "$mb"
		printf '        can take minutes. Reset it (local rooms, players and progress on celld are lost):\n'
		printf '        rm -rf %q\n' "$state"
	fi
}

# start_celld <project> <port> <relay port>: `celld dev` with the cells
# worker in <project> (its state persists in <project>/.celld/dev), relaying
# the outbox Queue to the game server on <relay port>. Sets CELLD_PID,
# CELLD_URL and DISTRIBUTED_INTERNAL_SECRET (persisted in the project).
# CELLD_EXTRA_VARS (newline-terminated `KEY=value` lines) adds worker vars.
start_celld() {
	local project="$1" port="$2" relay_port="$3"
	ensure_celld
	ensure_cells
	warn_celld_state "$project/.celld/dev"
	mkdir -p "$project"
	rm -rf "$project/build"
	cp -R "$CELLS/build" "$project/build"
	cp "$CELLS/wrangler.jsonc" "$project/wrangler.jsonc"
	if [[ ! -s "$project/internal-secret" ]]; then
		(umask 077 && printf 'test-only-%s' "$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')" >"$project/internal-secret")
	fi
	DISTRIBUTED_INTERNAL_SECRET="$(cat "$project/internal-secret")"
	printf 'DISTRIBUTED_INTERNAL_SECRET=%s\nCELLD_QUEUE_RELAY_URL=http://127.0.0.1:%s/internal/celld-queue/relay\n%s' \
		"$DISTRIBUTED_INTERNAL_SECRET" "$relay_port" "${CELLD_EXTRA_VARS:-}" >"$project/.dev.vars"
	log "starting celld dev on :$port ($("$CELLD_BIN" --version 2>/dev/null | grep '^celld ' | head -1); state in $project/.celld/dev)"
	# One node: no ownership balancing (its sampler walks every cell).
	CELLD_REBALANCE_INTERVAL_MS="${CELLD_REBALANCE_INTERVAL_MS:-0}" RUST_LOG=warn "$CELLD_BIN" dev "$project" --host 127.0.0.1 --port "$port" --no-watch --logs >"$project/celld.log" 2>&1 &
	CELLD_PID=$!
	CELLD_URL="http://127.0.0.1:$port"
	for _ in $(seq 1 300); do
		curl -fsS "$CELLD_URL/health" >/dev/null 2>&1 && break
		if ! kill -0 "$CELLD_PID" 2>/dev/null; then
			tail -20 "$project/celld.log"
			echo "celld dev failed to start" >&2
			exit 1
		fi
		sleep 0.2
	done
	curl -fsS "$CELLD_URL/health" >/dev/null || { tail -20 "$project/celld.log"; echo "celld dev not ready" >&2; exit 1; }
	export CELLD_URL DISTRIBUTED_INTERNAL_SECRET
}

ensure_server() {
	log "building game-demos server"
	cargo build --quiet --manifest-path "$SERVER/Cargo.toml"
}

ensure_cli() {
	log "building distributed CLI"
	cargo build --quiet --manifest-path "$REPO/Cargo.toml" -p distributed_cli --bin distributed
}

# gen [--check]: GameSurface JSON from each Rust surface export → typed
# TypeScript in client/src/generated/<surface>/ (surface.json included, so a
# changed Rust definition shows up as drift), then the surface's predicted
# step and pure functions → <surface>/wasm/<surface>.wasm. `--check` only
# applies to the checked-in TypeScript; the WASM is a build output and is
# (re)built.
gen() {
	local check="${1:-}"
	ensure_cli
	local tmp status=0
	tmp="$(mktemp -d "${TMPDIR:-/tmp}/game-surfaces.XXXXXX")"
	for surface in "${SURFACES[@]}"; do
		"$CLI" game-manifest --manifest-path "$SERVER/Cargo.toml" \
			--entrypoint "game_demos::$surface::game_surface" --out "$tmp/$surface.json" &&
			"$CLI" game-client --manifest "$tmp/$surface.json" \
				--out "$CLIENT/src/generated/$surface" $check &&
			wasm_for "$tmp/$surface.json" "$surface" ||
			status=1
	done
	rm -rf "$tmp"
	return "$status"
}

# wasm_for <surface.json> <surface>: compile the surface's `#[predict]` step
# and `#[game_pure]` functions (if it declares any) next to its generated
# client.
wasm_for() {
	grep -q -e '"predict"' -e '"pures"' "$1" || return 0
	"$CLI" game-wasm --manifest "$1" --manifest-path "$SERVER/Cargo.toml" \
		--out "$CLIENT/src/generated/$2" >/dev/null
}

# ensure_wasm: build every module the pages load (no TypeScript generation;
# the stamps make this quick when nothing changed).
ensure_wasm() {
	ensure_cli
	log "compiling predicted steps and pure functions to WebAssembly"
	local tmp status=0
	tmp="$(mktemp -d "${TMPDIR:-/tmp}/game-surfaces.XXXXXX")"
	for surface in "${SURFACES[@]}"; do
		"$CLI" game-manifest --manifest-path "$SERVER/Cargo.toml" \
			--entrypoint "game_demos::$surface::game_surface" --out "$tmp/$surface.json" &&
			wasm_for "$tmp/$surface.json" "$surface" ||
			status=1
	done
	rm -rf "$tmp"
	return "$status"
}

# dev_secret <dir> [name]: a dev secret persisted in <dir>/<name> (default
# dev-ticket-secret: the ticket secret; Mob Pit's services read the same
# file). Persisted so a returning browser is the same player after a
# restart: its guest token (or session cookie) still verifies.
dev_secret() {
	local file="$1/${2:-dev-ticket-secret}"
	mkdir -p "$1"
	if [[ ! -s "$file" ]]; then
		(umask 077 && od -An -N32 -tx1 /dev/urandom | tr -d ' \n' >"$file")
	fi
	cat "$file"
}

# start_fleet <dir> <relay port> <nodes> <ticket secret>: a local multi-node
# celld in production mode — one RustFS container (docker compose; Dory
# publishes ports for compose, not for plain `docker run`) holding the
# fleet bucket, the cells worker deployed to it (`celld deploy`, vars
# inlined), N nodes. Sets FLEET_PIDS, FLEET_PROJECT, FLEET_COMPOSE,
# CELLD_URL (node-a, for the services), ROOMS_URLS (a round-robin load
# balancer over every node, for browsers: scripts/round-robin.mjs) and
# DISTRIBUTED_INTERNAL_SECRET.
start_fleet() {
	local dir="$1" relay_port="$2" nodes="$3" ticket_secret="$4"
	local base="${GAME_DEMOS_PORT:-2567}"
	local s3_port="${MOBPIT_FLEET_S3_PORT:-$((base + 30))}"
	ensure_celld
	ensure_cells
	for tool in docker aws python3; do
		command -v "$tool" >/dev/null || { echo "--fleet needs $tool" >&2; exit 1; }
	done
	mkdir -p "$dir"
	export AWS_ACCESS_KEY_ID=mobpitfleet AWS_SECRET_ACCESS_KEY=mobpitfleetsecret AWS_REGION=us-east-1
	export S3_ENDPOINT="http://127.0.0.1:$s3_port"
	FLEET_PROJECT="mobpit-fleet-$base"
	FLEET_COMPOSE="$dir/s3-compose.yaml"
	cat >"$FLEET_COMPOSE" <<YAML
services:
  s3:
    image: rustfs/rustfs:1.0.3
    command: ["/data"]
    environment:
      RUSTFS_ADDRESS: "0.0.0.0:9000"
      RUSTFS_ACCESS_KEY: $AWS_ACCESS_KEY_ID
      RUSTFS_SECRET_KEY: $AWS_SECRET_ACCESS_KEY
    ports: ["127.0.0.1:$s3_port:9000"]
    volumes: ["fleet-data:/data"]
volumes:
  fleet-data: {}
YAML
	log "starting RustFS for the fleet bucket ($FLEET_PROJECT, :$s3_port)"
	docker compose -p "$FLEET_PROJECT" -f "$FLEET_COMPOSE" up -d >/dev/null
	for _ in $(seq 1 60); do
		aws --endpoint-url "$S3_ENDPOINT" s3 mb s3://mobpit-fleet >/dev/null 2>&1 && break
		aws --endpoint-url "$S3_ENDPOINT" s3 ls s3://mobpit-fleet >/dev/null 2>&1 && break
		sleep 1
	done
	if [[ ! -s "$dir/internal-secret" ]]; then
		(umask 077 && printf 'test-only-%s' "$(od -An -N24 -tx1 /dev/urandom | tr -d ' \n')" >"$dir/internal-secret")
	fi
	DISTRIBUTED_INTERNAL_SECRET="$(cat "$dir/internal-secret")"
	local names=(a b c d e f) nodes_var="" i
	for ((i = 0; i < nodes; i++)); do
		nodes_var+="${nodes_var:+,}node-${names[$i]}=127.0.0.1:$((base + 20 + i))"
	done
	rm -rf "$dir/worker" && mkdir -p "$dir/worker"
	cp -R "$CELLS/build" "$dir/worker/build"
	python3 - "$CELLS/wrangler.jsonc" "$dir/worker/wrangler.json" <<PY
import json, sys
text = "\n".join(l for l in open(sys.argv[1]) if not l.lstrip().startswith("//"))
config = json.loads(text)
config["vars"].update({
    "DISTRIBUTED_INTERNAL_SECRET": "$DISTRIBUTED_INTERNAL_SECRET",
    "GAME_TICKET_SECRET": "$ticket_secret",
    "CELLD_QUEUE_RELAY_URL": "http://127.0.0.1:$relay_port/internal/celld-queue/relay",
    "CELLD_ZONE_NODES": "$nodes_var",
})
json.dump(config, open(sys.argv[2], "w"))
PY
	log "deploying the cells worker (rooms + cells) to s3://mobpit-fleet/fleet"
	"$CELLD_BIN" deploy "$dir/worker" --bucket s3://mobpit-fleet/fleet 2>&1 | grep -E "Version ID|rror" || true
	FLEET_PIDS=()
	ROOMS_URLS=""
	for ((i = 0; i < nodes; i++)); do
		local name="node-${names[$i]}" ndir="$dir/node-${names[$i]}"
		mkdir -p "$ndir"
		CELLD_NODE="$name" CELLD_WATCH="$ndir/watch" RUST_LOG="${RUST_LOG:-warn}" \
			CELLD_IDLE_EVICT_S="${CELLD_IDLE_EVICT_S:-60}" CELLD_READY_FLEET_GATE_MS=0 \
			"$CELLD_BIN" --bucket s3://mobpit-fleet/fleet --listen "127.0.0.1:$((base + 10 + i))" \
			--internal-listen "127.0.0.1:$((base + 20 + i))" --advertise "127.0.0.1:$((base + 20 + i))" \
			>"$ndir/celld.log" 2>&1 &
		FLEET_PIDS+=($!)
		ROOMS_URLS+="${ROOMS_URLS:+,}http://127.0.0.1:$((base + 10 + i))"
	done
	for ((i = 0; i < nodes; i++)); do
		for _ in $(seq 1 120); do
			curl -fsS "http://127.0.0.1:$((base + 10 + i))/health" >/dev/null 2>&1 && break
			sleep 0.5
		done
		curl -fsS "http://127.0.0.1:$((base + 10 + i))/health" >/dev/null || {
			tail -20 "$dir/node-${names[$i]}/celld.log"
			echo "fleet node-${names[$i]} did not start" >&2
			exit 1
		}
		log "node-${names[$i]}: http://127.0.0.1:$((base + 10 + i))  (operator :$((base + 20 + i)), logs $dir/node-${names[$i]}/celld.log)"
	done
	CELLD_URL="http://127.0.0.1:$((base + 10))"
	# One entry point for browsers, spreading connections over the nodes
	# like a production load balancer would (placement stays celld's).
	local lb_port="${MOBPIT_FLEET_LB_PORT:-$((base + 9))}"
	node "$HERE/scripts/round-robin.mjs" "$lb_port" "$(echo "$ROOMS_URLS" | sed 's#http://##g')" >"$dir/lb.log" 2>&1 &
	FLEET_PIDS+=($!)
	for _ in $(seq 1 50); do grep -q LISTENING "$dir/lb.log" && break; sleep 0.1; done
	log "load balancer: http://127.0.0.1:$lb_port → $ROOMS_URLS (round robin per connection)"
	ROOMS_URLS="http://127.0.0.1:$lb_port"
	export CELLD_URL DISTRIBUTED_INTERNAL_SECRET
}

stop_fleet() {
	[[ -n "${FLEET_PROJECT:-}" ]] || return 0
	kill "${FLEET_PIDS[@]}" 2>/dev/null || true
	wait "${FLEET_PIDS[@]}" 2>/dev/null || true
	docker compose -p "$FLEET_PROJECT" -f "$FLEET_COMPOSE" down -v >/dev/null 2>&1 || true
}

# Mob Pit: rooms on celld (`celld dev`, or a local fleet with --fleet [N]),
# the services (`game-demos mobpit`: tickets, read models, boards) and Vite.
run_mobpit() {
	local demo="$1" fleet="${2:-}" nodes="${3:-3}"
	local port="${GAME_DEMOS_PORT:-2567}"
	local client_port="${GAME_DEMOS_CLIENT_PORT:-5173}"
	ensure_sdk
	ensure_client
	ensure_server
	ensure_wasm
	local secret
	secret="$(dev_secret "$MOBPIT_DATA_DIR")"
	CELLD_PID=""
	FLEET_PROJECT=""
	if [[ "$fleet" == --fleet ]]; then
		start_fleet "$MOBPIT_DATA_DIR/fleet" "$port" "$nodes" "$secret"
	else
		CELLD_EXTRA_VARS="GAME_TICKET_SECRET=$secret"$'\n'"CELLD_ZONE_NODE=celld-dev"$'\n'
		start_celld "$MOBPIT_DATA_DIR/celld" "${CELLD_PORT:-$((port + 3))}" "$port"
		ROOMS_URLS="$CELLD_URL"
	fi
	local log_file
	log_file="$(mktemp -t game-demos.XXXXXX)"
	local admin
	admin="$(dev_secret "$MOBPIT_DATA_DIR" admin-secret)"
	# The services' gateway routes `/zones/{room}` to the rooms (celld, or
	# the fleet's load balancer); Vite proxies game traffic to it only.
	DISTRIBUTED_GAME_SECRET="$secret" DG_DEMO_ADMIN_SECRET="$admin" "$BIN" mobpit --dev --port "$port" \
		--data-dir "$MOBPIT_DATA_DIR" --celld-url "$CELLD_URL" --zones-origin "$ROOMS_URLS" >"$log_file" 2>&1 &
	local server_pid=$!
	trap 'kill "$server_pid" 2>/dev/null || true; wait "$server_pid" 2>/dev/null || true; [[ -z "$CELLD_PID" ]] || kill_tree "$CELLD_PID"; stop_fleet; rm -f "$log_file"' EXIT INT TERM
	wait_listening "$log_file" "$server_pid" "game-demos mobpit"
	sed -n '2p' "$log_file"
	echo
	log "open  http://localhost:$client_port/$demo/   (gateway + services :$port, rooms on celld ${ROOMS_URLS}; dev routes ON — local only)"
	log "admin http://localhost:$client_port/mobpit/?admin=$admin   (live content updates; add &old=1 in another tab for an old client)"
	echo
	cd "$CLIENT"
	GAME_DEMOS_SERVER="http://127.0.0.1:$port" GAME_DEMOS_CLIENT_PORT="$client_port" npx vite
}

wait_listening() {
	local log_file="$1" pid="$2" what="$3"
	for _ in $(seq 1 100); do
		grep -q '^LISTENING' "$log_file" && return 0
		if ! kill -0 "$pid" 2>/dev/null; then
			cat "$log_file"
			echo "$what failed to start" >&2
			exit 1
		fi
		sleep 0.1
	done
}

# api_keys: an ES256 key pair for the SvelteKit server's read-model Bearer
# tokens — sets API_SIGNING_JWK (private, for the UI) and API_JWKS (public,
# for mobpit-service). Fresh per run; nothing is written to disk.
api_keys() {
	local keys
	keys="$(node -e '
		const { generateKeyPairSync, randomBytes } = require("node:crypto");
		const { privateKey, publicKey } = generateKeyPairSync("ec", { namedCurve: "P-256" });
		const kid = randomBytes(8).toString("hex");
		const priv = { ...privateKey.export({ format: "jwk" }), kid, alg: "ES256" };
		const pub = { ...publicKey.export({ format: "jwk" }), kid, alg: "ES256", use: "sig" };
		process.stdout.write(JSON.stringify(priv) + "\n" + JSON.stringify({ keys: [pub] }));
	')"
	API_SIGNING_JWK="$(sed -n 1p <<<"$keys")"
	API_JWKS="$(sed -n 2p <<<"$keys")"
}

# require_redis: the SvelteKit demo's leaderboard is the Redis board the
# zone server writes and mobpit-service serves (REDIS_URL).
require_redis() {
	if [[ -z "${REDIS_URL:-}" ]]; then
		echo "REDIS_URL is required: the SvelteKit leaderboard is the Redis board" >&2
		echo "  (docker compose up -d redis at the repo root, then REDIS_URL=redis://127.0.0.1:6379)" >&2
		exit 1
	fi
}

# The SvelteKit demo: the Mob Pit zone server (publishing Crawler domain
# events and board change notices to a SQLite bus, kills into the Redis
# boards), then `distributed dev server/`, which generates the
# `$distributed` GraphQL client, runs mobpit-service (the player_stats read
# model and the Redis boards, GraphQL @live) and `vite dev` (the Vite plugin
# also generates src/lib/generated/mobpit and its WASM on start and on Rust
# changes).
run_sveltekit() {
	require_redis
	local fleet="${1:-}" nodes="${2:-3}"
	local port="${GAME_DEMOS_PORT:-2967}"
	local ui_port="${SVELTEKIT_PORT:-5573}"
	local service_port="${MOBPIT_SERVICE_PORT:-$((port + 2))}"
	local data="${MOBPIT_DATA_DIR%/}-sveltekit"
	ensure_sdk
	ensure_sveltekit
	ensure_server
	ensure_cli
	mkdir -p "$data"
	local secret
	secret="$(dev_secret "$data")"
	CELLD_PID=""
	FLEET_PROJECT=""
	if [[ "$fleet" == --fleet ]]; then
		GAME_DEMOS_PORT="$port" start_fleet "$data/fleet" "$port" "$nodes" "$secret"
	else
		CELLD_EXTRA_VARS="GAME_TICKET_SECRET=$secret"$'\n'"CELLD_ZONE_NODE=celld-dev"$'\n'
		start_celld "$data/celld" "${CELLD_PORT:-$((port + 3))}" "$port"
		ROOMS_URLS="$CELLD_URL"
	fi
	local log_file
	log_file="$(mktemp -t game-demos-sveltekit.XXXXXX)"
	DISTRIBUTED_GAME_SECRET="$secret" "$BIN" mobpit --port "$port" --celld-url "$CELLD_URL" \
		--data-dir "$data" --projection-bus "sqlite:$data/bus.db" \
		--redis-url "$REDIS_URL" >"$log_file" 2>&1 &
	local server_pid=$!
	trap 'kill "$server_pid" 2>/dev/null || true; wait "$server_pid" 2>/dev/null || true; [[ -z "$CELLD_PID" ]] || kill_tree "$CELLD_PID"; stop_fleet; rm -f "$log_file"' EXIT INT TERM
	wait_listening "$log_file" "$server_pid" "game-demos mobpit"
	api_keys
	echo
	log "open  http://localhost:$ui_port/   (sign in with any username; rooms on celld ${ROOMS_URLS}, services :$port, read model :$service_port; dev sign-in — local only)"
	echo
	# mobpit-service (the lifecycle's runtime) and the UI share these.
	BIND="127.0.0.1:$service_port" UI_PORT="$ui_port" \
		DATABASE_URL="sqlite:$data/service.db?mode=rwc" MOBPIT_BUS_URL="sqlite:$data/bus.db" \
		MOBPIT_API_ISSUER=mobpit-sveltekit MOBPIT_API_AUDIENCE=mobpit-service \
		MOBPIT_API_JWKS="$API_JWKS" MOBPIT_API_SIGNING_JWK="$API_SIGNING_JWK" \
		MOBPIT_PROTOCOL_KEY="$(od -An -N32 -tx1 /dev/urandom | tr -d ' \n')" \
		MOBPIT_UI_ORIGINS="http://localhost:$ui_port,http://127.0.0.1:$ui_port" \
		MOBPIT_GRAPHQL_URL="http://127.0.0.1:$service_port/graphql" \
		GAME_DEV_AUTH=1 AUTH_SECRET="${AUTH_SECRET:-$(dev_secret "$data" auth-secret)}" \
		GAME_TICKET_SECRET="$secret" GAME_ZONES_URL="$(echo "$ROOMS_URLS" | sed 's#http://#ws://#g')" \
		"$CLI" dev "$SERVER"
}

smoke() {
	ensure_sdk
	ensure_client
	# The celld-backed tests start their own `celld dev` (CELLD_BIN) on
	# the cells worker.
	ensure_celld
	ensure_cells
	# The SvelteKit test's leaderboard is the Redis board. Only that test gets
	# REDIS_URL: the other demos' tests expect their in-memory boards.
	require_redis
	local sveltekit_redis="$REDIS_URL"
	unset REDIS_URL
	log "generated clients are current; predicted steps and pure functions compiled to WASM"
	gen --check
	log "server: fmt, clippy, tests (bots smoke)"
	cargo fmt --manifest-path "$SERVER/Cargo.toml" --check -p game_demos -p game_sim -p mobpit_crawler -p mobpit_service -p mobpit_rooms -p mobpit_tiers
	cargo fmt --manifest-path "$CELLS/Cargo.toml" --check
	cargo clippy --quiet --manifest-path "$SERVER/Cargo.toml" --workspace --all-targets -- -D warnings
	cargo clippy --quiet --manifest-path "$CELLS/Cargo.toml" --target wasm32-unknown-unknown -- -D warnings
	cargo test --quiet --manifest-path "$SERVER/Cargo.toml" --workspace
	cargo build --quiet --manifest-path "$SERVER/Cargo.toml" --workspace --bins
	log "client: type-check, build, tests (WASM steps + pure functions exact match, headless SDK)"
	(cd "$CLIENT" && npm run --silent check && npx vite build --logLevel warn && GAME_DEMOS_BIN="$BIN" npm test --silent)
	log "sveltekit: generated game client current; distributed build (GraphQL client, svelte-check, vite build + game codegen/WASM); headless Playwright"
	ensure_sveltekit
	ensure_cli
	(cd "$SVELTEKIT" && npm run --silent check:games)
	local build_log
	build_log="$(mktemp -t game-demos-build.XXXXXX)"
	"$CLI" build "$SERVER" >"$build_log" 2>&1 || { cat "$build_log"; rm -f "$build_log"; exit 1; }
	rm -f "$build_log"
	(cd "$SVELTEKIT" && npx playwright install chromium >/dev/null &&
		REDIS_URL="$sveltekit_redis" GAME_DEMOS_BIN="$BIN" MOBPIT_SERVICE_BIN="$SERVICE_BIN" npm test --silent)
	log "smoke OK"
}

case "${1:-}" in
	smoke) smoke ;;
	gen) gen "${2:-}" ;;
	sveltekit) run_sveltekit "${2:-}" "${3:-3}" ;;
	list) printf '%s\n' "${DEMOS[@]}" sveltekit ;;
	"" | -h | --help | help) awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0" ;;
	*)
		if [[ " ${DEMOS[*]} " == *" $1 "* ]]; then
			run_mobpit "$1" "${2:-}" "${3:-3}"
		else
			echo "unknown demo '$1' (known: ${DEMOS[*]})" >&2
			exit 2
		fi
		;;
esac
