//! Blob game module: the `blob.*` Atomic commands. Each seals its
//! `BlobGames` row ([`SaveBlobGame`], the `BLOB_GAMES` projection's own
//! mutation) in the command's transaction, so the commands live here, next to
//! the read models, and not in `blob-domain`.

use blob_domain::{domain_commands, BlobGame, BlobGameState, Direction, PREVIEW_MOVE};
use distributed::command;
use distributed::command::{Atomic, CommandProjectionPureReduce, PreparedCommand};
use distributed::command_input_defaults;
use distributed::microsvc::{
    guards, AggregateDependencies, CausalCommandContext, HandlerError, Routes, ServiceStores,
};
use e2e_projections::SaveBlobGame;
use e2e_readmodels::BlobGames;
use serde::Deserialize;

/// Mount the blob Atomic commands.
pub fn routes<St: ServiceStores>(stores: &St) -> Routes<AggregateDependencies<St, BlobGame>> {
    Routes::for_aggregate(stores)
        .mount(start())
        .mount(move_dir())
        .mount(start_level())
}

fn sealed_row(game: &BlobGame) -> Result<BlobGames, HandlerError> {
    SaveBlobGame()
        .from_state(&BlobGameState::from(game))
        .map_err(|error| HandlerError::Other(Box::new(error)))
}

#[derive(Debug, Deserialize, distributed::CommandInput)]
pub struct BlobStartInput {
    /// Generated by the client (`uuid_v7()`), so the page can navigate to the
    /// new game before the server answers.
    pub game_id: String,
}

pub async fn handle_start(
    ctx: &CausalCommandContext<'_, BlobGame>,
    input: BlobStartInput,
) -> Result<PreparedCommand<Atomic<BlobGames>>, HandlerError> {
    let owner = ctx.user_id()?.to_string();
    let repo = ctx.repo();
    if repo.get(&input.game_id).await?.is_some() {
        return Err(HandlerError::Rejected(format!(
            "game {} already exists",
            input.game_id
        )));
    }
    let mut game = repo.create();
    game.start_with_demo(&input.game_id, &owner)
        .map_err(HandlerError::rejected)?;
    let row = sealed_row(&*game)?;
    repo.readmodel(row).publish_events().commit(game)?.atomic()
}

command! {
    name: "blob.start",
    transition: domain_commands::StartWithMap,
    aggregate: BlobGame,
    input: BlobStartInput,
    outcome: Atomic<BlobGames>,
    shard: |input| input.game_id.clone(),
    roles: ["user", "admin"],
    field: "blob_games_start",
    guard: guards::authenticated,
    handle: handle_start,
    defaults: command_input_defaults! {
        input: BlobStartInput;
        default input.game_id = uuid_v7();
    },
}

#[derive(Debug, Deserialize, distributed::CommandInput)]
pub struct BlobMoveInput {
    pub game_id: String,
    /// `up` | `down` | `left` | `right`
    pub direction: String,
}

pub async fn handle_move(
    ctx: &CausalCommandContext<'_, BlobGame>,
    input: BlobMoveInput,
) -> Result<PreparedCommand<Atomic<BlobGames>>, HandlerError> {
    let owner = ctx.user_id()?.to_string();
    let direction = Direction::parse(&input.direction).ok_or_else(|| {
        HandlerError::Rejected(format!(
            "invalid direction `{}` (use up|down|left|right)",
            input.direction
        ))
    })?;
    let repo = ctx.repo();
    let mut game = repo
        .get(&input.game_id)
        .await?
        .ok_or_else(|| HandlerError::NotFound(input.game_id.clone()))?;
    game.move_dir(&owner, direction)
        .map_err(HandlerError::rejected)?;
    let row = sealed_row(&*game)?;
    repo.readmodel(row).publish_events().commit(game)?.atomic()
}

command! {
    name: "blob.move",
    transition: domain_commands::MoveDir,
    aggregate: BlobGame,
    input: BlobMoveInput,
    outcome: Atomic<BlobGames>,
    shard: |input| input.game_id.clone(),
    roles: ["user", "admin"],
    field: "blob_games_move",
    constructor: move_dir,
    // The browser runs the domain's own `simulate_move` (WASM) over the known
    // row; key, argument and patched columns come from the Rust types.
    preview_reduce_known_record: CommandProjectionPureReduce::known_record::<BlobGames>(PREVIEW_MOVE),
    guard: guards::authenticated,
    handle: handle_move,
}

#[derive(Debug, Deserialize, distributed::CommandInput)]
pub struct BlobStartLevelInput {
    pub game_id: String,
}

pub async fn handle_start_level(
    ctx: &CausalCommandContext<'_, BlobGame>,
    input: BlobStartLevelInput,
) -> Result<PreparedCommand<Atomic<BlobGames>>, HandlerError> {
    let owner = ctx.user_id()?.to_string();
    let repo = ctx.repo();
    let mut game = repo
        .get(&input.game_id)
        .await?
        .ok_or_else(|| HandlerError::NotFound(input.game_id.clone()))?;
    game.start_next_generated_level(&owner)
        .map_err(HandlerError::rejected)?;
    let row = sealed_row(&*game)?;
    repo.readmodel(row).publish_events().commit(game)?.atomic()
}

command! {
    name: "blob.start_level",
    transition: domain_commands::StartLevel,
    aggregate: BlobGame,
    input: BlobStartLevelInput,
    outcome: Atomic<BlobGames>,
    shard: |input| input.game_id.clone(),
    roles: ["user", "admin"],
    field: "blob_games_start_level",
    guard: guards::authenticated,
    handle: handle_start_level,
}

#[cfg(test)]
mod tests {
    use super::*;
    use distributed::cell_host::instance_name;
    use distributed::{Aggregate, AggregateBuilder, InMemoryRepository};

    #[test]
    fn atomic_commands_mount_with_their_projection_contracts() {
        let specs = Routes::new()
            .with_repo(InMemoryRepository::new().aggregate::<BlobGame>())
            .mount(start())
            .mount(move_dir())
            .mount(start_level())
            .command_specs()
            .expect("blob command declarations compile");

        for command in ["blob.start", "blob.move", "blob.start_level"] {
            let spec = specs
                .iter()
                .find(|spec| spec.id == command)
                .unwrap_or_else(|| panic!("missing {command}"));
            assert_eq!(
                spec.projected_model.as_deref(),
                Some("BlobGames"),
                "{command} should be Atomic<BlobGames>"
            );
        }

        let move_spec = specs.iter().find(|spec| spec.id == "blob.move").unwrap();
        let pure = &move_spec.projection_contract["pure_reduces"][0];
        assert_eq!(pure["fn_name"], "blob-domain::preview_move", "{pure}");
        assert_eq!(pure["wasm_package"], "wasm/blob-domain/blob_domain");
        assert_eq!(pure["wasm_export"], "preview_move");
        assert_eq!(pure["model"], "BlobGames");
        assert_eq!(pure["key"][0]["name"], "game_id");
        assert_eq!(pure["args"][0]["name"], "direction");
        assert_eq!(
            pure["assign"],
            serde_json::json!([
                "current_level_completed",
                "map",
                "moves",
                "player_dead",
                "score",
                "status"
            ])
        );
    }

    #[test]
    fn a_move_addresses_its_game_cell() {
        let input = BlobMoveInput {
            game_id: "g1".into(),
            direction: "up".into(),
        };
        let shard = Move::shard(&input);
        assert_eq!(
            instance_name::<BlobGame>(&shard),
            format!("{}:{}", BlobGame::aggregate_type(), shard)
        );
        assert_eq!(instance_name::<BlobGame>(&shard), "blob:g1");
    }
}
